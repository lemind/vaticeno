"""One password, one cookie (003 US1). Standard library only — no new dependency for this.

The page is the owner's; there are no accounts, no registration and no reset, so a password hash in the
environment and a signed cookie are the whole of it. This is not the user auth constitution VII rules out:
there is nothing to log into but this page, and nothing behind it can be written.
"""

from __future__ import annotations

import hmac
import os
import time
from base64 import urlsafe_b64decode, urlsafe_b64encode
from hashlib import scrypt, sha256
from secrets import compare_digest, token_bytes

COOKIE = "vaticeno_status"
SESSION_SECONDS = 7 * 24 * 3600

# This password is the only lock on the page, and there is no account to recover, so it is held to a
# length rather than to character classes.
MIN_PASSWORD_CHARS = 12

# scrypt at the parameters Python's own docs use for interactive logins.
_N, _R, _P = 2**14, 8, 1


def hash_password(password: str) -> str:
    """`scrypt$<salt>$<key>`, for STATUS_PASSWORD_HASH. Generated by `python -m status.hash_password`."""
    salt = token_bytes(16)
    key = scrypt(password.encode(), salt=salt, n=_N, r=_R, p=_P)
    return f"scrypt${_b64(salt)}${_b64(key)}"


def check_password(password: str, stored: str) -> bool:
    """False for a wrong password and for a malformed or missing hash alike: no configuration, no entry."""
    try:
        scheme, salt, key = stored.split("$")
    except ValueError:
        return False
    if scheme != "scrypt":
        return False
    try:
        computed = scrypt(password.encode(), salt=_unb64(salt), n=_N, r=_R, p=_P)
    except ValueError:
        return False
    return compare_digest(computed, _unb64(key))


def issue(secret: str, now: float | None = None) -> str:
    """A cookie value that carries its own expiry and is signed with the server secret."""
    expires = int((now if now is not None else time.time()) + SESSION_SECONDS)
    return f"{expires}.{_sign(secret, str(expires))}"


def valid(cookie: str | None, secret: str, now: float | None = None) -> bool:
    if not cookie or not secret:
        return False
    expires, _, signature = cookie.partition(".")
    if not signature or not compare_digest(signature, _sign(secret, expires)):
        return False
    try:
        return int(expires) > (now if now is not None else time.time())
    except ValueError:
        return False


def _sign(secret: str, payload: str) -> str:
    return _b64(hmac.new(secret.encode(), payload.encode(), sha256).digest())


def configured() -> tuple[str, str] | None:
    """The hash and the signing secret, or None — in which case the page refuses everyone rather than
    letting everyone in. A missing password is never an open door."""
    stored = os.environ.get("STATUS_PASSWORD_HASH", "")
    secret = os.environ.get("STATUS_SECRET", "")
    return (stored, secret) if stored and secret else None


def _b64(raw: bytes) -> str:
    return urlsafe_b64encode(raw).decode().rstrip("=")


def _unb64(text: str) -> bytes:
    return urlsafe_b64decode(text + "=" * (-len(text) % 4))
