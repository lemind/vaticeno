"""Each run's `report*.md` from its `report*.json` (003 T343b): the same numbers, as tables. Numbers only, no
dataset pair.

    .venv-train/bin/python -m verifier.train.report
"""

import json
import sys

from verifier.train.evaluate import REPORT
from verifier.train.finetune import CONFIG

# What each base's own authors report on MNLI matched, with their recipe: context for this run, never its score.
REFERENCES = {
    "nreimers/MiniLM-L6-H384-uncased": "the MiniLM paper reports 83.3% on MNLI matched for this architecture",
    "microsoft/deberta-v3-xsmall": "the DeBERTa-v3 authors report 88.1% on MNLI matched (88.3% mismatched)",
}

NAMES = {
    "mnli_matched_validation": "MNLI matched (validation)",
    "mnli_matched_validation_non_fiction": "  of which non-fiction",
    "mnli_matched_validation_fiction": "  of which fiction (not trained on)",
    "mnli_mismatched_validation": "MNLI mismatched (validation)",
    "snli_test": "SNLI test (not trained on)",
}
ENGINEERING = (
    ("file_mib", "File, MiB"),
    ("peak_rss_mib", "Peak RSS, MiB"),
    ("cold_start_s", "Cold start, s"),
    ("latency_ms_128_tokens", "Latency, 128 tokens, ms"),
    ("latency_ms_512_tokens", "Latency, 512 tokens, ms"),
)


def markdown(r: dict) -> str:
    run, a = r["model"]["run"], r["artefacts"]
    epochs = run["steps"] / -(-run["train_pairs"] // CONFIG["batch_size"])
    reference = REFERENCES.get(r["model"]["base"])
    lines = [
        "# Practice model: report\n",
        f"Generated by `verifier/train/report.py` from `{REPORT.name}` (003 T343b, decision 004). Numbers only.\n",
        "## Training\n",
        f"{r['model']['base']} fine-tuned on MultiNLI train without fiction: {run['train_pairs']:,} pairs, "
        f"{run['development_pairs']:,} held out as the development split. {run['steps']:,} steps, {epochs:.3g} epochs, "
        f"{run['seconds'] / 60:.0f} minutes on a {run['device']} (torch {run['torch']}). "
        f"Best development accuracy {run['best_dev_accuracy']:.2%}.\n",
        "## Benchmarks, scored once\n",
        "| Set | n | fp32 accuracy | int8 accuracy | fp32 macro-F1 | int8 macro-F1 |",
        "|---|---|---|---|---|---|",
    ]
    for key, label in NAMES.items():
        f, i = a["fp32"]["sets"][key]["raw"], a["int8"]["sets"][key]["raw"]
        lines.append(f"| {label} | {f['n']:,} | {f['accuracy']:.1%} | {i['accuracy']:.1%} | "
                     f"{f['macro_f1']:.3f} | {i['macro_f1']:.3f} |")
    if reference:
        lines.append(f"\nReference: {reference} after fine-tuning on all of MultiNLI with their own recipe; "
                     "not a score of this run.\n")
    lines += [
        "## Calibration\n",
        f"Temperature fitted on each artefact's own development-split logits: fp32 T = {a['fp32']['temperature']}, "
        f"int8 T = {a['int8']['temperature']}.\n",
        "| Set | artefact | ECE raw → calibrated | Brier raw → calibrated | error among the 25% most confident |",
        "|---|---|---|---|---|",
    ]
    for key in ("mnli_mismatched_validation", "snli_test"):
        for art in ("fp32", "int8"):
            v = a[art]["sets"][key]
            lines.append(f"| {NAMES[key]} | {art} | {v['raw']['ece']:.3f} → {v['calibrated']['ece']:.3f} | "
                         f"{v['raw']['brier']:.3f} → {v['calibrated']['brier']:.3f} | "
                         f"{v['raw']['error_at_coverage']['0.25']:.1%} |")
    lines += ["\n## Challenge set (60 hand-written pairs, frozen before training; diagnostic only)\n",
              "| Group | fp32 | int8 |", "|---|---|---|"]
    for group in a["fp32"]["challenge"]:
        fp32, int8 = a["fp32"]["challenge"][group], a["int8"]["challenge"][group]
        lines.append(f"| {group.replace('_', ' ')} | {fp32} | {int8} |")
    lines += ["\nTwelve pairs a group: one pair moves a group by 8 points. Shows failure types, not a ranking.\n",
              "## Engineering (this laptop, one thread, bare process with the ONNX session)\n",
              "| | fp32 | int8 |", "|---|---|---|"]
    for key, label in ENGINEERING:
        lines.append(f"| {label} | {a['fp32']['engineering'][key]} | {a['int8']['engineering'][key]} |")
    sha = {art: a[art]["engineering"]["sha256"] for art in ("fp32", "int8")}
    lines.append(f"\nsha256: fp32 `{sha['fp32']}`, int8 `{sha['int8']}`.\n")
    return "\n".join(lines) + "\n"


def main() -> int:
    (REPORT.with_suffix(".md")).write_text(markdown(json.loads(REPORT.read_text())))
    return 0


if __name__ == "__main__":
    sys.exit(main())
